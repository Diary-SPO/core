function buildCtx(region: DiaryRegion): RegionCtx {
  const cities = regionCities(region)
  const cityList =
    cities.length === 0
      ? null
      : cities.length === 1
        ? cities[0]
        : `${cities.slice(0, -1).join(', ')} и ${cities[cities.length - 1]}`
  return {
    host: new URL(region.url).hostname,
    cities,
    cityList,
    codeLabel: regionCodeWithName(region),
    spoLabel: spoCodeWithName(region),
    mainCity: cities[0] ?? null
  }
}

