export function getRegionPageContent(region: DiaryRegion): RegionPageContent {
  const ctx = buildCtx(region)
  const factory = BY_ID[region.id] ?? fallback
  const content = factory(region, ctx)
  if (region.hasEsiaOnly && region.note) {
    const already = content.notes.some((n) => n.text.includes(region.note!))
    if (!already) {
      content.notes = [
        { variant: 'warn', title: 'Важно', text: region.note },
        ...content.notes
      ]
    }
  }
  return content
}
